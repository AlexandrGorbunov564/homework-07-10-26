CREATE TABLE IF NOT EXISTS payments (
id SERIAL PRIMARY KEY ,
income NUMERIC(15, 2) NOT NULL,
percent NUMERIC(6, 2) NOT NULL ,
tax NUMERIC(15, 2) NOT NULL ,
created_at TIMESTAMP DEFAULT now()
);